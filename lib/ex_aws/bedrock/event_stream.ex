defmodule ExAws.Bedrock.EventStream do
  @moduledoc """
  Handle streaming of output generated by models.

  The model detail returned by `ExAws.Bedrock.get_foundation_model/1` must have:

      responseStreamingSupported = true

  This requires `hackney` otherwise we will fail at runtime. It also assumes `Jason` is available
  but we can improve this to lookup the ExAws JSON coded.

  [AWS API Docs](https://docs.aws.amazon.com/bedrock/latest/APIReference/API_runtime_ResponseStream.html)
  """

  defdelegate build_request_url(post_operation, config), to: ExAws.Request.Url, as: :build

  @content_type "application/vnd.amazon.eventstream"

  if {:module, :hackney} == Code.ensure_loaded(:hackney) &&
       Kernel.function_exported?(:hackney, :post, 4) do
    # hackney >= 4 moved default_ua/0 from :hackney_request to :hackney
    if function_exported?(:hackney, :default_ua, 0) do
      @http_ua :hackney.default_ua()
    else
      @http_ua :hackney_request.default_ua()
    end

    @library_version Application.spec(:ex_aws_bedrock)[:vsn]
    @user_agent "#{@http_ua} ex_aws/bedrock/#{@library_version}"
    @headers [
      {"accept", @content_type},
      {"content-type", "application/json"},
      {"user-agent", @user_agent},
      {"x-amzn-bedrock-accept", "*/*"}
    ]
    # :protocols forces HTTP/1.1: hackney >= 4 negotiates HTTP/2 via ALPN by
    # default, but its h2 path does not deliver async body messages, so the
    # event stream would hang waiting for chunks that never arrive. HTTP/1.1
    # also guarantees the chunked transfer-encoding this module verifies.
    @hackney_options [{:async, :once}, {:protocols, [:http1]}]

    @doc """
    Stream of chunks from the response stream.

    Raises on any error.

    [AWS API Docs](https://docs.aws.amazon.com/bedrock/latest/APIReference/API_runtime_ResponseStream.html)
    """
    def stream_objects!(%{service: service, data: data} = post_operation, _opts, config) do
      encoded_data = Jason.encode!(data)
      url = build_request_url(post_operation, config)
      config = Map.put(config, :service_override, :bedrock)

      {:ok, full_headers} =
        ExAws.Auth.headers(
          :post,
          url,
          service,
          config,
          @headers,
          encoded_data
        )

      hackney_opts = hackney_options(config)

      request_fun = fn [] ->
        {:ok, ref} = :hackney.post(url, full_headers, encoded_data, hackney_opts)

        receive do
          {:hackney_response, ^ref, {:status, 200, _reason}} ->
            ref

          {:hackney_response, ^ref, {:status, status, reason}} ->
            {:error, status, reason}

          {:hackney_response, ^ref, {:error, {:closed, :timeout}}} ->
            :closed

          {:hackney_response, ^ref, {:error, reason}} ->
            raise ExAws.Error, "Bedrock stream request failed: #{inspect(reason)}"
        end
      end

      stream =
        Stream.resource(
          fn -> request_fun.([]) end,
          fn
            :closed ->
              {:halt, []}

            {:error, status, reason} ->
              raise ExAws.Error, "#{to_string(status)}: #{to_string(reason)}"

            # hackney < 4 identifies async responses by reference,
            # hackney >= 4 by the connection pid.
            ref when is_reference(ref) or is_pid(ref) ->
              :ok = :hackney.stream_next(ref)

              receive do
                {:hackney_response, ^ref, {:headers, headers}} ->
                  verify_event_stream!(headers)
                  verify_chunked!(headers)
                  {[], ref}

                {:hackney_response, ^ref, :done} ->
                  {:halt, []}

                {:hackney_response, ^ref, {:error, reason}} ->
                  raise ExAws.Error, "Bedrock stream failed mid-stream: #{inspect(reason)}"

                {:hackney_response, ^ref, data} when is_binary(data) ->
                  {[data], ref}

                {:hackney_response, ^ref, other} ->
                  raise ExAws.Error,
                        "Bedrock stream received unexpected message: #{inspect(other)}"
              end
          end,
          &Function.identity/1
        )

      decode_stream(stream)
    end

    @doc """
    Builds the hackney options for the streaming request.

    Merges caller-provided options from the ExAws config `:http_opts` (e.g.
    `recv_timeout`, `connect_timeout`, `pool`) on top of the async-streaming
    defaults. Without this, the stream would always use hackney's built-in
    `recv_timeout` (5s) and drop slow responses regardless of the timeout the
    caller configured.

    The streaming defaults win on conflicting keys, so the async-streaming mode
    (`async: :once`) and the forced HTTP/1.1 protocol can't be accidentally
    disabled by caller options.
    """
    def hackney_options(config) do
      config
      |> Map.get(:http_opts, [])
      |> Keyword.merge(@hackney_options)
    end

    defp verify_event_stream!(headers) do
      verify_header!(headers, "Content-Type", @content_type)
    end

    defp verify_chunked!(headers) do
      verify_header!(headers, "Transfer-Encoding", "chunked")
    end

    defp verify_header!(headers, header, expected) do
      case List.keyfind!(headers, header, 0) do
        {_, ^expected} ->
          true

        {_, content_type} ->
          raise ExAws.Error, "Accepts #{expected}, received #{to_string(content_type)}"
      end
    end
  else
    def stream_objects!(_, _, _) do
      raise "Bedrock response streaming requires hackney in your mix dependencies"
    end
  end

  @uint32_size 4
  @checksum_size 4
  # prelude_length = message_total_length + headers_length + prelude_checksum
  @prelude_length @uint32_size * 3
  # message_overhead = prelude + message_checksum
  @message_overhead @prelude_length + @checksum_size
  # The limits the AWS SDKs enforce on a message. A prelude declaring more is
  # rejected up front, so no more than one message is ever buffered.
  @max_headers_length 128 * 1024
  @max_payload_length 24 * 1024 * 1024

  @typep decoded :: {:chunk, map()} | {:bad_chunk, binary(), term()}

  @doc false
  # Decodes a stream of binaries into event stream messages.
  #
  # The transport gives no guarantee that a binary holds a whole number of
  # messages: a message may be split across any number of binaries. Bytes are
  # buffered until the message length declared in the prelude has arrived.
  #
  # Bytes left over when the stream ends are reported as a bad or incomplete
  # chunk.
  @spec decode_stream(Enumerable.t()) :: Enumerable.t()
  def decode_stream(stream) do
    # Runs once, before the first binary: nothing is buffered yet.
    empty_buffer = fn -> <<>> end

    # Runs for every binary: emit the whole messages, keep the rest buffered.
    decode_binary = fn data, buffer -> decode_messages(buffer <> data, []) end

    # Runs once, after the last binary: report bytes that never made a message.
    report_leftover = fn buffer -> {leftover(buffer), <<>>} end

    # Runs last, also when the consumer stops early: nothing to clean up.
    no_cleanup = fn _buffer -> :ok end

    Stream.transform(stream, empty_buffer, decode_binary, report_leftover, no_cleanup)
  end

  @doc false
  @spec decode_chunk(binary()) :: list(decoded() | {:incomplete_chunk, binary()})
  def decode_chunk(data) do
    {chunks, rest} = decode_messages(data, [])
    chunks ++ leftover(rest)
  end

  # Bytes that do not make up a whole message once there is no more data.
  defp leftover(<<>>), do: []

  defp leftover(rest) when byte_size(rest) < @prelude_length,
    do: [{:incomplete_chunk, rest}]

  defp leftover(rest), do: [{:bad_chunk, rest, :invalid_chunk}]

  # Decodes every complete message in the buffer, returning the bytes of a
  # trailing partial message so they can be prepended to the next binary.
  @spec decode_messages(binary(), list(decoded())) :: {list(decoded()), binary()}
  defp decode_messages(buffer, acc) do
    case split_message(buffer) do
      {:ok, message, rest} ->
        decode_messages(rest, [decode_message(message) | acc])

      :incomplete ->
        {Enum.reverse(acc), buffer}

      {:error, reason} ->
        # The declared length cannot be trusted so the start of the next
        # message is unknown: discard the buffer.
        {Enum.reverse([{:bad_chunk, buffer, reason} | acc]), <<>>}
    end
  end

  defp split_message(
         <<
           message_total_length::unsigned-32,
           headers_length::unsigned-32,
           prelude_checksum::unsigned-32,
           _::binary
         >> = buffer
       ) do
    prelude = <<message_total_length::unsigned-32, headers_length::unsigned-32>>

    cond do
      crc32(prelude) != prelude_checksum ->
        {:error, :invalid_prelude_checksum}

      message_total_length < @message_overhead + headers_length ->
        {:error, :invalid_chunk}

      headers_length > @max_headers_length ->
        {:error, :headers_too_large}

      message_total_length - @message_overhead - headers_length > @max_payload_length ->
        {:error, :payload_too_large}

      byte_size(buffer) < message_total_length ->
        :incomplete

      true ->
        <<message::binary-size(^message_total_length), rest::binary>> = buffer
        {:ok, message, rest}
    end
  end

  defp split_message(_buffer), do: :incomplete

  defp decode_message(
         <<_message_total_length::unsigned-32, headers_length::unsigned-32, _::binary>> = message
       ) do
    checked_length = byte_size(message) - @checksum_size
    body_length = checked_length - @prelude_length - headers_length

    <<
      checked::binary-size(^checked_length),
      message_checksum::unsigned-32
    >> = message

    <<
      _prelude::binary-size(@prelude_length),
      _headers::binary-size(^headers_length),
      body::binary-size(^body_length)
    >> = checked

    with :ok <- verify_message_checksum(checked, message_checksum),
         {:ok, chunk} <- process_chunk(body) do
      {:chunk, chunk}
    else
      {:error, reason} -> {:bad_chunk, message, reason}
    end
  end

  defp verify_message_checksum(message, checksum) do
    if crc32(message) == checksum do
      :ok
    else
      {:error, :invalid_message_checksum}
    end
  end

  defp crc32(data) do
    :erlang.crc32(data)
  end

  defp process_chunk(body) do
    with {:ok, %{"bytes" => bytes}} <- Jason.decode(body),
         {:ok, json} <- Base.decode64(bytes),
         {:ok, payload} <- Jason.decode(json) do
      {:ok, payload}
    else
      {:error, error} ->
        {:error, error}

      error ->
        {:error, error}
    end
  end
end
